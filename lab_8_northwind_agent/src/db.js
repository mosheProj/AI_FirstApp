import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { config } from './config.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, '..');

export const schemaPath = join(rootDir, 'sql', 'northwind.sql');
export const dataPath = join(rootDir, 'sql', 'northwind-data.sql');

const { Pool } = pg;
let pool;

function getConnectionConfig() {
  return {
    host: config.db.host,
    port: config.db.port,
    user: config.db.user,
    password: config.db.password,
    database: config.db.database,
  };
}

function wait(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

export async function waitForDatabase(maxAttempts = 30) {
  for (let attempt = 1; attempt <= maxAttempts; attempt += 1) {
    try {
      const testPool = new Pool(getConnectionConfig());
      await testPool.query('SELECT 1');
      await testPool.end();
      return;
    } catch (error) {
      if (attempt === maxAttempts) {
        throw error;
      }
      console.log(`Waiting for Postgres... attempt ${attempt}/${maxAttempts}`);
      await wait(3000);
    }
  }
}

export async function getPool() {
  if (!pool) {
    pool = new Pool({
      ...getConnectionConfig(),
      max: 10,
    });
  }

  return pool;
}

export async function closePool() {
  if (pool) {
    await pool.end();
    pool = undefined;
  }
}

function cleanupSql(sqlText) {
  return sqlText
    .split(/\r?\n/)
    .filter((line) => {
      const trimmed = line.trim();
      return (
        trimmed &&
        !trimmed.startsWith('#') &&
        !trimmed.startsWith('SET ') &&
        !trimmed.startsWith('USE ') &&
        !trimmed.startsWith('DROP SCHEMA') &&
        !trimmed.startsWith('CREATE SCHEMA')
      );
    })
    .join('\n');
}

export function convertDataSql(mysqlData) {
  return cleanupSql(mysqlData)
    .replace(/`northwind`\./g, '')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/([,(]\s*)default(?=\s*[,)]|$)/gi, '$1"default"');
}

function convertColumnLine(line) {
  let converted = line
    .replace(/`northwind`\./g, '')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\bnorthwind\./g, '')
    .replace(/^default\s+/i, '"default" ')
    .replace(/\bINT\(\d+\)/gi, 'INTEGER')
    .replace(/\bTINYINT\(\d+\)/gi, 'SMALLINT')
    .replace(/\bDOUBLE\b/gi, 'DOUBLE PRECISION')
    .replace(/\bDATETIME\b/gi, 'TIMESTAMP')
    .replace(/\bLONGTEXT\b/gi, 'TEXT')
    .replace(/\bLONGBLOB\b/gi, 'TEXT')
    .replace(/\bAUTO_INCREMENT\b/gi, 'GENERATED BY DEFAULT AS IDENTITY')
    .replace(/\s+DEFAULT\s+NULL/gi, '')
    .replace(/\s+CHARACTER\s+SET\s+\w+/gi, '')
    .replace(/\s+COLLATE\s+\w+/gi, '');

  return converted;
}

function convertConstraintLine(line) {
  return line
    .replace(/`northwind`\./g, '')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\bnorthwind\./g, '')
    .replace(/\s+ASC\b/gi, '');
}

function normalizeTableBody(body) {
  const lines = body
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .filter((line) => !/^INDEX\s+/i.test(line));

  const convertedLines = lines.map((line) => {
      if (/^(PRIMARY KEY|CONSTRAINT|FOREIGN KEY)/i.test(line)) {
        return convertConstraintLine(line);
      }
      return convertColumnLine(line);
    });

  if (convertedLines.length > 0) {
    const lastIndex = convertedLines.length - 1;
    convertedLines[lastIndex] = convertedLines[lastIndex].replace(/,\s*$/, '');
  }

  return convertedLines.join('\n');
}

export function convertSchemaSql(mysqlSchema) {
  const tableStatements = [];
  const pattern =
    /CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+`northwind`\.`([^`]+)`\s*\(([\s\S]*?)\)\s*ENGINE\s*=\s*InnoDB[\s\S]*?;/gi;
  let match;

  while ((match = pattern.exec(mysqlSchema)) !== null) {
    const [, tableName, body] = match;
    const tableBody = normalizeTableBody(body).replace(/,\s*\n\)/g, '\n)');
    tableStatements.push(`CREATE TABLE IF NOT EXISTS ${tableName} (\n${tableBody}\n);`);
  }

  return tableStatements.join('\n\n');
}

export async function executeNorthwindSchema() {
  const schema = await readFile(schemaPath, 'utf8');
  const dbPool = await getPool();
  await dbPool.query(convertSchemaSql(schema));
}

export async function loadNorthwindData() {
  const data = await readFile(dataPath, 'utf8');
  const dbPool = await getPool();

  const tables = await dbPool.query(`
    SELECT tablename
    FROM pg_tables
    WHERE schemaname = 'public'
      AND tablename <> 'schema_vector_chunks'
    ORDER BY tablename
  `);

  if (tables.rows.length > 0) {
    const tableNames = tables.rows
      .map((row) => `"${row.tablename.replaceAll('"', '""')}"`)
      .join(', ');
    await dbPool.query(`TRUNCATE TABLE ${tableNames} RESTART IDENTITY CASCADE`);
  }

  try {
    await dbPool.query('SET session_replication_role = replica');
    await dbPool.query(convertDataSql(data));
  } finally {
    await dbPool.query('SET session_replication_role = DEFAULT');
  }
}

export async function ensureVectorTable() {
  const dbPool = await getPool();
  await dbPool.query(`
    CREATE TABLE IF NOT EXISTS schema_vector_chunks (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      chunk_key VARCHAR(128) NOT NULL,
      chunk_text TEXT NOT NULL,
      embedding TEXT NOT NULL,
      embedding_model VARCHAR(100) NOT NULL,
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
  `);
}
